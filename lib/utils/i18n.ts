export const LANGUAGE_CHANGE_EVENT = "qz_language_changed";

export function getAppLanguage(): AppLanguage {
  if (typeof window === "undefined") return "en";
  const saved = localStorage.getItem("qz_lang");
  if (saved === "hi" || saved === "en") return saved;
  return "en";
}

export function setAppLanguage(lang: AppLanguage) {
  if (typeof window === "undefined") return;
  localStorage.setItem("qz_lang", lang);
  window.dispatchEvent(new CustomEvent(LANGUAGE_CHANGE_EVENT, { detail: { lang } }));
}

export function useAppLanguage() {
  const [lang, setLang] = useState<AppLanguage>("en");

  useEffect(() => {
    setLang(getAppLanguage());

    const handleLanguageChange = (e: Event) => {
      const customEvent = e as CustomEvent<{ lang?: AppLanguage }>;
      if (customEvent.detail?.lang) {
        setLang(customEvent.detail.lang);
      } else {
        setLang(getAppLanguage());
      }
    };

    window.addEventListener(LANGUAGE_CHANGE_EVENT, handleLanguageChange);
    return () => window.removeEventListener(LANGUAGE_CHANGE_EVENT, handleLanguageChange);
  }, []);

  const t = DICTIONARY[lang] || DICTIONARY.en;
  return { lang, t, setLanguage: setAppLanguage };
}

